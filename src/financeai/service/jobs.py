"""Allowlisted job commands shared by Python callers, the CLI path and the HTTP service.

A job command is a frozen, validated value. Its canonical mapping (:meth:`to_mapping`) is
the normalized request: defaults are filled in, synthetic venues are sorted, cache IDs are
sorted and the inline strategy is the strict canonical form of
:mod:`financeai.service.canonical` (lossy numeric spellings are rejected, equivalent ones
normalized), so equivalent requests hash identically (:func:`request_hash`) and the recorded
strategy is exactly the one that runs. No command carries a module path, code or a
filesystem path; ``strategy_replay`` names registered artifact IDs that the coordinator
resolves under ``STATE_ROOT``.

Execution reuses the CLI application path exactly (``financeai run``): strategy config ->
tape caches -> :func:`~financeai.application.strategy.load_market` ->
:func:`~financeai.application.strategy.run_strategy` ->
:func:`~financeai.application.strategy.write_run_outputs`. A synthetic job first writes its
generated tapes as immutable caches, so its replay reads memory-mapped caches like the CLI.
``checkpoint`` is called at safe boundaries; a worker uses it for cooperative cancellation.
Before replaying, the market's last clock plus the replay horizon (order latency, then the
longer of acknowledgement latency and consumption TTL, plus cooldown) must fit int64: the
numerical engine does not check its derived clocks and would wrap them silently.
"""

from __future__ import annotations

from collections.abc import Callable, Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Any, ClassVar, Final

from financeai.application.strategy import StrategyConfig, load_market, run_strategy, write_run_outputs
from financeai.core.errors import InvalidConfigError, InvalidDataError
from financeai.core.hashing import sha256_json
from financeai.domains.market.cache import save_tapes
from financeai.domains.market.scenario import demo_scenarios
from financeai.domains.market.synthetic import GENERATOR, SyntheticMarketSpec, synthetic_source, synthetic_tapes
from financeai.service.artifacts import tree_digest
from financeai.service.canonical import canonical_config, canonical_strategy, load_strategy
from financeai.service.store import is_artifact_id

JOB_KINDS: Final = ("synthetic_replay", "strategy_replay")
REQUEST_SCHEMA: Final = "financeai.run_request/1"
MAX_CACHES: Final = 16
RUN_OUTPUTS: Final = (
    ("run/summary.json", "run_summary"),
    ("run/fills.csv", "fills_csv"),
    ("run/orders.csv", "orders_csv"),
    ("run/strategy.json", "strategy_config"),
)
"""Files written by ``write_run_outputs`` (paths relative to the attempt directory)."""

Checkpoint = Callable[[str, int, int], None]


def _no_checkpoint(phase: str, completed: int, total: int) -> None:
    return None


def _exact_keys(doc: Mapping[str, Any], required: set[str], optional: set[str], where: str) -> None:
    keys = set(doc)
    missing, extra = required - keys, keys - required - optional
    if missing or extra:
        raise InvalidConfigError(f"{where}: keys differ", context={"missing": sorted(missing), "extra": sorted(extra)})


def _check_scenario(name: object) -> str:
    known = demo_scenarios()
    if not isinstance(name, str) or name not in known:
        raise InvalidConfigError("unknown scenario", context={"got": name, "known": list(known)})
    return name


def venue_dirname(key: str) -> str:
    """Directory name of a generated venue cache (instrument keys contain a slash)."""
    return key.replace("/", "__")


@dataclass(frozen=True)
class SyntheticReplayJob:
    """Replay a strategy on a deterministic synthetic market (engineering evidence only)."""

    market: SyntheticMarketSpec
    scenario: str
    strategy: StrategyConfig
    kind: ClassVar[str] = "synthetic_replay"

    def __post_init__(self) -> None:
        if not isinstance(self.market, SyntheticMarketSpec) or not isinstance(self.strategy, StrategyConfig):
            raise InvalidConfigError("synthetic job needs a SyntheticMarketSpec and a StrategyConfig")
        object.__setattr__(self, "strategy", canonical_config(self.strategy))
        _check_scenario(self.scenario)
        missing = [k for k in self.strategy.instruments if k not in self.market.venues]
        if missing:
            raise InvalidConfigError(
                "strategy instruments are not generated by the synthetic market",
                context={"missing": missing, "venues": list(self.market.venues)},
            )

    @classmethod
    def from_mapping(cls, doc: Mapping[str, Any]) -> SyntheticReplayJob:
        _exact_keys(
            doc, {"kind", "seed", "venues", "scenario", "strategy"}, {"rows_per_venue", "start_ns"}, "synthetic_replay"
        )
        venues = doc["venues"]
        if not isinstance(venues, list | tuple):
            raise InvalidConfigError("venues must be a list of instrument keys")
        market = SyntheticMarketSpec(
            seed=doc["seed"],
            venues=tuple(venues),
            rows_per_venue=doc.get("rows_per_venue", 300),
            start_ns=doc.get("start_ns", 0),
        )
        return cls(market=market, scenario=doc["scenario"], strategy=canonical_strategy(doc["strategy"]))

    def to_mapping(self) -> dict[str, Any]:
        return {
            "kind": self.kind,
            **self.market.to_mapping(),
            "scenario": self.scenario,
            "strategy": self.strategy.to_mapping(),
        }

    @property
    def evidence_scope(self) -> tuple[str, ...]:
        return ("SYNTHETIC",)


@dataclass(frozen=True)
class StrategyReplayJob:
    """Replay a registered strategy artifact on registered tape-cache artifacts."""

    strategy_artifact_id: str
    cache_artifact_ids: tuple[str, ...]
    scenario: str
    kind: ClassVar[str] = "strategy_replay"

    def __post_init__(self) -> None:
        if not is_artifact_id(self.strategy_artifact_id):
            raise InvalidConfigError("strategy_artifact_id is not an artifact ID")
        caches = self.cache_artifact_ids
        if not isinstance(caches, tuple | list) or not 1 <= len(caches) <= MAX_CACHES:
            raise InvalidConfigError(f"cache_artifact_ids needs 1..{MAX_CACHES} artifact IDs")
        if not all(is_artifact_id(c) for c in caches) or len(set(caches)) != len(caches):
            raise InvalidConfigError("cache_artifact_ids must be distinct artifact IDs")
        object.__setattr__(self, "cache_artifact_ids", tuple(sorted(caches)))
        _check_scenario(self.scenario)

    @classmethod
    def from_mapping(cls, doc: Mapping[str, Any]) -> StrategyReplayJob:
        _exact_keys(doc, {"kind", "strategy_artifact_id", "cache_artifact_ids", "scenario"}, set(), "strategy_replay")
        caches = doc["cache_artifact_ids"]
        if not isinstance(caches, list | tuple):
            raise InvalidConfigError("cache_artifact_ids must be a list")
        return cls(
            strategy_artifact_id=doc["strategy_artifact_id"], cache_artifact_ids=tuple(caches), scenario=doc["scenario"]
        )

    def to_mapping(self) -> dict[str, Any]:
        return {
            "kind": self.kind,
            "strategy_artifact_id": self.strategy_artifact_id,
            "cache_artifact_ids": list(self.cache_artifact_ids),
            "scenario": self.scenario,
        }


Job = SyntheticReplayJob | StrategyReplayJob


def job_from_mapping(doc: Mapping[str, Any]) -> Job:
    """Validate a job mapping against the allowlist of job kinds."""
    if not isinstance(doc, Mapping):
        raise InvalidConfigError("job must be an object")
    kind = doc.get("kind")
    if kind == SyntheticReplayJob.kind:
        return SyntheticReplayJob.from_mapping(doc)
    if kind == StrategyReplayJob.kind:
        return StrategyReplayJob.from_mapping(doc)
    raise InvalidConfigError("unknown job kind", context={"got": kind, "allowed": list(JOB_KINDS)})


def request_hash(campaign_id: str, job: Job) -> str:
    """Idempotency hash of the normalized command (no credentials, no wall-clock metadata)."""
    return sha256_json({"schema": REQUEST_SCHEMA, "campaign_id": campaign_id, "job": job.to_mapping()})


def expected_outputs(job: Job) -> tuple[tuple[str, str], ...]:
    """``(relative path, artifact kind)`` of everything a successful attempt must publish."""
    if isinstance(job, SyntheticReplayJob):
        caches = tuple((f"caches/{venue_dirname(k)}", "tape_cache") for k in job.market.venues)
        return RUN_OUTPUTS + caches
    return RUN_OUTPUTS


def _empty_dir(path: str | Path) -> Path:
    out = Path(path)
    out.mkdir(parents=True, exist_ok=True)
    if any(out.iterdir()):
        raise InvalidConfigError("output directory must be empty", context={"name": out.name})
    return out


def _replay(
    cfg: StrategyConfig, cache_dirs: Sequence[Path], scenario_name: str, out: Path, checkpoint: Checkpoint
) -> dict[str, Any]:
    prep = load_market(cache_dirs, cfg.instruments)
    scenario = demo_scenarios(prep.data.instruments)[_check_scenario(scenario_name)]
    checkpoint("replay", 2, 4)
    result = run_strategy(prep, cfg, scenario)
    checkpoint("write", 3, 4)
    return write_run_outputs(result, prep, cfg, scenario, out / "run")


def run_synthetic_replay(
    job: SyntheticReplayJob, out_dir: str | Path, *, checkpoint: Checkpoint = _no_checkpoint
) -> dict[str, Any]:
    """Synchronous synthetic replay into an empty ``out_dir``; returns the run summary."""
    out = _empty_dir(out_dir)
    checkpoint("generate", 0, 4)
    tapes = synthetic_tapes(job.market)
    caches = []
    for key in job.market.venues:
        target = out / "caches" / venue_dirname(key)
        save_tapes(tapes[key], target, source=synthetic_source(job.market, key), parser=GENERATOR)
        caches.append(target)
    checkpoint("load", 1, 4)
    return _replay(job.strategy, caches, job.scenario, out, checkpoint)


def run_strategy_replay(
    strategy_path: str | Path,
    cache_dirs: Sequence[str | Path],
    scenario: str,
    out_dir: str | Path,
    *,
    checkpoint: Checkpoint = _no_checkpoint,
) -> dict[str, Any]:
    """Synchronous replay of a strategy file on tape caches (the ``financeai run`` path).

    The file is read strictly and canonicalized (:func:`~financeai.service.canonical.load_strategy`),
    so lossy numeric spellings are refused here too and the run records the canonical strategy.
    """
    cfg = load_strategy(strategy_path)
    out = _empty_dir(out_dir)
    checkpoint("load", 1, 4)
    return _replay(cfg, [Path(c) for c in cache_dirs], scenario, out, checkpoint)


def _verified_input(entry: Mapping[str, Any]) -> Path:
    path = Path(entry["path"])
    digest, size = tree_digest(path)
    if digest != entry["sha256"] or size != entry["size_bytes"]:
        raise InvalidDataError("registered input artifact changed on disk", context={"artifact_id": entry["id"]})
    return path


def execute_job(payload: Mapping[str, Any], staging: Path, checkpoint: Checkpoint) -> dict[str, Any]:
    """Worker entry: run a normalized job into ``staging`` and describe what was written.

    ``payload`` holds ``job`` (the normalized mapping) and, for ``strategy_replay``, the
    coordinator-resolved ``inputs`` (paths inside the artifact store plus registered digests,
    re-verified here before use). The descriptor lists every output with its digest; the
    coordinator re-hashes them before anything is published.
    """
    job = job_from_mapping(payload["job"])
    if isinstance(job, SyntheticReplayJob):
        run_synthetic_replay(job, staging, checkpoint=checkpoint)
    else:
        checkpoint("verify", 0, 4)
        inputs = payload["inputs"]
        strategy = _verified_input(inputs["strategy"])
        caches = [_verified_input(c) for c in inputs["caches"]]
        run_strategy_replay(strategy, caches, job.scenario, staging, checkpoint=checkpoint)
    outputs = []
    for rel_path, kind in expected_outputs(job):
        digest, size = tree_digest(staging / rel_path)
        outputs.append({"rel_path": rel_path, "kind": kind, "sha256": digest, "size_bytes": size})
    return {"outputs": outputs}


def result_from_summary(summary: Mapping[str, Any]) -> dict[str, Any]:
    """The run result recorded with a committed run (clocks stay int64 here)."""
    return {
        "scenario": str(summary["scenario"]),
        "account_valid": bool(summary["valid"]),
        "invalid_reason": summary["reason"],
        "net_pnl": summary["net_pnl"],
        "settlement_currencies": list(summary.get("settlement_currencies", [])),
        "pnl_by_currency": summary.get("pnl_by_currency"),
        "fees_per_unit": dict(summary.get("fees_per_unit", {})),
        "round_trips": int(summary["round_trips"]),
        "fills": int(summary["fills"]),
        "orders": int(summary["orders"]),
        "decisions": int(summary["decisions"]),
        "first_event_ns": int(summary["first_event_ns"]),
        "last_event_ns": int(summary["last_event_ns"]),
        "fees": {str(k): str(v) for k, v in dict(summary["fees"]).items()},
    }
